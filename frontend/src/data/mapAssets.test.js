import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { mapImages } from './mapImages'
import { playableBounds } from './playableBounds'

const here = path.dirname(fileURLToPath(import.meta.url))
const assetsRoot = path.resolve(here, '../assets/maps')
const semanticsRoot = path.resolve(here, '../../../common/map-semantics')

function readSemantics() {
  return fs.readdirSync(semanticsRoot)
    .filter(file => file.endsWith('.semantic.json'))
    .map(file => JSON.parse(fs.readFileSync(path.join(semanticsRoot, file), 'utf8')))
}

const semantics = readSemantics()

/**
 * 3D asset-pack terrain meta golden (verification oracle, never imported by production).
 *
 * Source: https://assets.wotbtools.com/map/<base mapCode>/terrain.json `playableBounds`,
 * fetched 2026-11-01 for the 29 base mapCodes shared with the generated 2D table.
 * The production pack is generated by the upstream WoT-Blitz-Agent repo and cannot be
 * regenerated here; this snapshot makes the 2D generated table ↔ 3D terrain meta parity
 * deterministic in CI. Refresh it when the asset pack's playable bounds change.
 */
const terrainGolden = JSON.parse(fs.readFileSync(path.join(here, '__golden__/terrainPlayableBounds.json'), 'utf8'))

function readWebpDimensions(file) {
  const data = fs.readFileSync(file)
  if (data.length < 20 || data.toString('ascii', 0, 4) !== 'RIFF' || data.toString('ascii', 8, 12) !== 'WEBP') {
    throw new Error(`Not a WebP file: ${file}`)
  }
  let offset = 12
  while (offset + 8 <= data.length) {
    const type = data.toString('ascii', offset, offset + 4)
    const size = data.readUInt32LE(offset + 4)
    const start = offset + 8
    if (start + size > data.length) throw new Error(`Truncated WebP chunk ${type}: ${file}`)
    if (type === 'VP8X') {
      if (size < 10) throw new Error(`Invalid VP8X frame header: ${file}`)
      const width = 1 + data.readUIntLE(start + 4, 3)
      const height = 1 + data.readUIntLE(start + 7, 3)
      return { width, height }
    }
    if (type === 'VP8 ') {
      if (size < 10 || data[start + 3] !== 0x9d || data[start + 4] !== 0x01 || data[start + 5] !== 0x2a) {
        throw new Error(`Invalid VP8 frame header: ${file}`)
      }
      return {
        width: data.readUInt16LE(start + 6) & 0x3fff,
        height: data.readUInt16LE(start + 8) & 0x3fff,
      }
    }
    if (type === 'VP8L') {
      if (size < 5 || data[start] !== 0x2f) throw new Error(`Invalid VP8L frame header: ${file}`)
      const b1 = data[start + 1]
      const b2 = data[start + 2]
      const b3 = data[start + 3]
      const b4 = data[start + 4]
      return {
        width: 1 + b1 + ((b2 & 0x3f) << 8),
        height: 1 + ((b2 & 0xc0) >> 6) + (b3 << 2) + ((b4 & 0x0f) << 10),
      }
    }
    offset = start + size + (size % 2)
  }
  throw new Error(`No image dimensions found in WebP: ${file}`)
}

describe('2D Local basemap asset contract', () => {
  it('registers every canonical WebP exactly once and decodes its dimensions', () => {
    const images = Object.values(mapImages)
    const files = images.map(image => {
      expect(image.src).toContain('/assets/maps/')
      const file = path.basename(image.src.split('?')[0])
      const dimensions = readWebpDimensions(path.join(assetsRoot, file))
      expect(dimensions.width, file).toBeGreaterThan(0)
      expect(dimensions.height, file).toBeGreaterThan(0)
      expect(image.width, file).toBeGreaterThan(0)
      expect(image.height, file).toBeGreaterThan(0)
      return file
    })
    expect(images).toHaveLength(29)
    expect(new Set(files).size).toBe(images.length)
    expect(files.sort()).toEqual(fs.readdirSync(assetsRoot).filter(file => file.endsWith('.webp')).sort())
  })

  it('keeps registered map codes and render bounds aligned with semantic world bounds', () => {
    for (const [mapCode, image] of Object.entries(mapImages)) {
      const semantic = semantics.find(item => item.mapCodes.includes(mapCode))
      expect(semantic, mapCode).toBeDefined()
      const { xMin, xMax, yMin, yMax } = semantic.coordinateSystem.worldBounds
      expect([xMin, xMax, yMin, yMax].every(Number.isFinite), mapCode).toBe(true)
      expect(xMax, mapCode).toBeGreaterThan(xMin)
      expect(yMax, mapCode).toBeGreaterThan(yMin)
      expect(image.coordinateBounds, mapCode).toEqual({ xMin, xMax, yMin, yMax })
    }
  })
})

const BOUNDS_KEYS = ['xMin', 'yMin', 'xMax', 'yMax']

/** Python `round(value, 1)` contract used by common/python/export_playable_bounds.py. */
function round1(value) {
  const scaled = value * 10
  const lower = Math.floor(scaled)
  const diff = scaled - lower
  if (Math.abs(diff - 0.5) < 1e-9) return (lower % 2 === 0 ? lower : lower + 1) / 10
  return Math.round(scaled) / 10
}

function roundedBounds(bounds) {
  return { xMin: round1(bounds.xMin), yMin: round1(bounds.yMin), xMax: round1(bounds.xMax), yMax: round1(bounds.yMax) }
}

function hasOneDecimal(value) {
  return Number.isFinite(value) && Math.abs(value * 10 - Math.round(value * 10)) < 1e-9
}

describe('playable bounds parity (semantic → generated → 3D terrain meta)', () => {
  const semanticByCode = new Map()
  for (const semantic of semantics) {
    if (!semantic.playableBoundsMeters) continue
    for (const code of semantic.mapCodes || []) semanticByCode.set(code, semantic)
  }

  it('matches the generated table for every semantic mapCode under the exporter round(...,1) contract', () => {
    expect(Object.keys(playableBounds).sort()).toEqual([...semanticByCode.keys()].sort())
    for (const [code, semantic] of semanticByCode) {
      const source = semantic.playableBoundsMeters
      for (const key of BOUNDS_KEYS) {
        expect(Number.isFinite(source[key]), `${code}.${key}`).toBe(true)
        expect(hasOneDecimal(source[key]), `${code}.${key} must stay on the 1-decimal contract`).toBe(true)
      }
      expect(playableBounds[code], code).toEqual(roundedBounds(source))
    }
  })

  it('matches the 3D asset-pack terrain meta golden for every shared map', () => {
    // The golden is a snapshot of the external asset pack; both sides must be the 29 base mapCodes.
    expect(Object.keys(terrainGolden).sort()).toEqual(Object.keys(playableBounds).sort())
    for (const [code, bounds] of Object.entries(playableBounds)) {
      const terrain = terrainGolden[code]
      expect(terrain, code).toBeDefined()
      for (const key of BOUNDS_KEYS) {
        expect(Number.isFinite(terrain[key]), `${code}.${key}`).toBe(true)
        expect(hasOneDecimal(terrain[key]), `${code}.${key} terrain precision`).toBe(true)
      }
      expect(roundedBounds(terrain), code).toEqual(bounds)
    }
  })

  it('keeps semantic maps without mapCodes out of the 2D table (fail-closed)', () => {
    const withoutCodes = semantics
      .filter(semantic => semantic.playableBoundsMeters && !(semantic.mapCodes || []).length)
      .map(semantic => semantic.mapId)
      .sort()
    // Known corpus state: these semantic files are not replay-addressable, so 2D must not guess a key.
    expect(withoutCodes).toEqual(['06_rudniki_rd', '30_grossberg_sh', '40_moon_mn', '41_iceworld_ic'])
    for (const code of ['rudniki', 'grossberg', 'moon', 'iceworld']) {
      expect(playableBounds[code], code).toBeUndefined()
      expect(terrainGolden[code], code).toBeUndefined()
    }
  })
})
