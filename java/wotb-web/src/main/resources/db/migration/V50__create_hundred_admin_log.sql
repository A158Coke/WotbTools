-- 名人堂「百场」管理员删除审计（V50）：submission 物理删除后原行不存在，
-- 删除前状态快照必须完整落库（不能只存 submission_id FK），且本表不设指向
-- hundred_battle_submission 的外键（删除行不得连带审计）。
-- 与删除同一事务：audit 写入失败 → submission 不删；submission 删除失败 → 无假审计。
-- 沿用 V17 hall_of_fame_admin_log（Mark3 DELETE_ENTRY）的快照表模式；
-- 本表承载百场特有字段（status / claimed* / approved* / wotb_server）。
-- 注：V18 submission 表的 deleted_at/deleted_by/delete_reason/delete_reason_text
-- 为软删除时代遗留列，物理删除语义下不再写入（行即删），保留列仅为 schema 稳定。
create table hundred_admin_log (
    id bigint generated by default as identity primary key,

    action varchar(32) not null default 'DELETE_SUBMISSION',

    submission_id bigint not null,
    original_status varchar(16) not null,
    wotb_server varchar(16) not null,
    wotb_account_id bigint not null,
    vehicle_id bigint not null,
    vehicle_name varchar(100) not null,
    nickname_snapshot varchar(100) not null,

    claimed_average_damage integer not null,
    claimed_battle_count integer not null,
    approved_average_damage integer,
    approved_battle_count integer,

    had_proof_screenshot boolean not null default false,

    admin_keycloak_user_id varchar(64) not null,
    admin_username varchar(128),

    delete_reason varchar(64) not null,
    delete_reason_text varchar(500),

    -- V50 之前的软删除墓碑历史（仅 status='DELETED' 的行有值）：原软删事件的
    -- 操作者/时间/原因随 submission 行物理删除而消失，必须独立留存可追溯；
    -- 与本次物理删除事件的 admin_* / delete_reason 字段分开保存
    previous_deleted_at timestamp with time zone,
    previous_deleted_by varchar(64),
    previous_delete_reason varchar(64),
    previous_delete_reason_text varchar(500),

    created_at timestamp with time zone not null default now()
);

create index idx_hundred_admin_log_created_at
    on hundred_admin_log (created_at desc);

create index idx_hundred_admin_log_submission_id
    on hundred_admin_log (submission_id);

create index idx_hundred_admin_log_account
    on hundred_admin_log (wotb_server, wotb_account_id);
