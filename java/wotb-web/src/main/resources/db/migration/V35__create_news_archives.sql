CREATE TABLE news_archive (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source VARCHAR(16) NOT NULL CHECK (source = 'WG'),
 version VARCHAR(80) NOT NULL CHECK (length(btrim(version)) > 0),
 title VARCHAR(300) NOT NULL CHECK (length(btrim(title)) > 0),
 status VARCHAR(16) NOT NULL CHECK (status IN ('PREPARING','FAILED','PUBLISHED','WITHDRAWN')),
 revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reviewed_by VARCHAR(255) NOT NULL,
 published_at TIMESTAMP WITH TIME ZONE,
 attempt_token VARCHAR(36),
 lease_until TIMESTAMP WITH TIME ZONE,
 error_code VARCHAR(80),
 CHECK ((attempt_token IS NULL) = (lease_until IS NULL))
);
CREATE INDEX news_archive_public_idx ON news_archive(source,version,status,created_at DESC,id DESC);
CREATE INDEX news_archive_work_idx ON news_archive(status,lease_until,id);
CREATE TABLE news_archive_source (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 archive_id BIGINT NOT NULL REFERENCES news_archive(id) ON DELETE CASCADE,
 position INTEGER NOT NULL CHECK (position >= 0),
 article JSONB NOT NULL CHECK (jsonb_typeof(article) = 'object'),
 image_sources JSONB NOT NULL CHECK (jsonb_typeof(image_sources) = 'object'),
 UNIQUE(archive_id,position)
);
CREATE TABLE news_archive_category (
 archive_id BIGINT NOT NULL REFERENCES news_archive(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES news_category(id) ON DELETE RESTRICT,
 PRIMARY KEY(archive_id,category_id)
);
CREATE INDEX news_archive_category_reference_idx ON news_archive_category(category_id);
-- A minimal receipt survives explicit archive deletion, preventing retry resurrection.
CREATE TABLE news_receipt (
 id VARCHAR(512) PRIMARY KEY,
 payload_hash VARCHAR(64) NOT NULL,
 archive_ids JSONB NOT NULL CHECK (jsonb_typeof(archive_ids) = 'array')
);
-- Image reservations intentionally outlive archive deletion and failed external PUTs.
CREATE TABLE news_image (
 id VARCHAR(36) PRIMARY KEY,
 archive_id BIGINT NOT NULL,
 source_image_id VARCHAR(64) NOT NULL,
 source_url TEXT NOT NULL,
 object_key VARCHAR(255) NOT NULL UNIQUE,
 status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','READY','DELETING')),
 content_type VARCHAR(80),
 image_hash VARCHAR(64),
 size_bytes BIGINT,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 unreferenced_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(archive_id,source_image_id)
);
CREATE INDEX news_image_cleanup_idx ON news_image(unreferenced_at,created_at);
CREATE TABLE news_archive_image (
 archive_id BIGINT NOT NULL REFERENCES news_archive(id) ON DELETE CASCADE,
 image_id VARCHAR(36) NOT NULL REFERENCES news_image(id) ON DELETE RESTRICT,
 PRIMARY KEY(archive_id,image_id)
);
CREATE INDEX news_archive_image_reference_idx ON news_archive_image(image_id);
