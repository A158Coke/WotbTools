CREATE TABLE news_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 type VARCHAR(16) NOT NULL CHECK (type IN ('GENERAL','SPECIALIZED'))
);
