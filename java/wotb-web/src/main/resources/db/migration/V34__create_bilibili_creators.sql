CREATE TABLE creator_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0)
);
CREATE TABLE creator_level (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0)
);
CREATE TABLE creator (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 description VARCHAR(2000),
 homepage_url VARCHAR(300) NOT NULL,
 level_id BIGINT REFERENCES creator_level(id),
 base_stars INTEGER NOT NULL DEFAULT 3 CHECK (base_stars BETWEEN 1 AND 5),
 favorite_count BIGINT NOT NULL DEFAULT 0 CHECK (favorite_count >= 0),
 cycle_count BIGINT NOT NULL DEFAULT 0 CHECK (cycle_count >= 0),
 reward_points INTEGER NOT NULL DEFAULT 0 CHECK (reward_points BETWEEN 0 AND 8),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX creator_level_idx ON creator(level_id);
CREATE INDEX creator_public_order_idx ON creator((LEAST(10, base_stars * 2 + reward_points)) DESC, created_at DESC, id DESC);
CREATE TABLE creator_category_link (
 creator_id BIGINT NOT NULL REFERENCES creator(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES creator_category(id),
 PRIMARY KEY (creator_id, category_id)
);
CREATE INDEX creator_category_link_category_idx ON creator_category_link(category_id, creator_id);
-- History survives cancellation; no profile FK: JWT-only users can favorite as well.
CREATE TABLE creator_favorite (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 creator_id BIGINT NOT NULL REFERENCES creator(id) ON DELETE CASCADE,
 keycloak_subject VARCHAR(64) NOT NULL CHECK (length(btrim(keycloak_subject)) > 0),
 active BOOLEAN NOT NULL,
 UNIQUE (creator_id, keycloak_subject)
);
CREATE INDEX creator_favorite_subject_active_idx ON creator_favorite(keycloak_subject, active, creator_id);
