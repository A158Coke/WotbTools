CREATE TABLE creator_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0)
);
CREATE TABLE creator_level (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0)
);
-- Site-owned upload ledger: failed or interrupted saves remain discoverable for cleanup.
CREATE TABLE creator_avatar (
 id VARCHAR(36) PRIMARY KEY,
 object_key VARCHAR(512) NOT NULL UNIQUE,
 status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'READY')),
 content_type VARCHAR(32) NOT NULL CHECK (content_type IN ('image/png', 'image/jpeg')),
 size BIGINT NOT NULL CHECK (size > 0 AND size <= 524288),
 hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 unreferenced_at TIMESTAMP WITH TIME ZONE,
 last_cleanup_attempt_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX creator_avatar_cleanup_idx ON creator_avatar((coalesce(last_cleanup_attempt_at, unreferenced_at, created_at)), id);
CREATE TABLE creator (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bilibili_uid VARCHAR(20) NOT NULL UNIQUE CHECK (bilibili_uid ~ '^[1-9][0-9]{0,19}$'),
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 description VARCHAR(2000),
 level_id BIGINT REFERENCES creator_level(id),
 stars INTEGER NOT NULL DEFAULT 3 CHECK (stars BETWEEN 1 AND 5),
 avatar_id VARCHAR(36) UNIQUE REFERENCES creator_avatar(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX creator_level_idx ON creator(level_id);
CREATE INDEX creator_public_order_idx ON creator(stars DESC, created_at DESC, id DESC);
CREATE TABLE creator_category_link (
 creator_id BIGINT NOT NULL REFERENCES creator(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES creator_category(id),
 PRIMARY KEY (creator_id, category_id)
);
CREATE INDEX creator_category_link_category_idx ON creator_category_link(category_id, creator_id);
