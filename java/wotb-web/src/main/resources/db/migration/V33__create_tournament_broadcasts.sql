-- Broadcast seasons are independent from tournament points events and their rules.
CREATE TABLE tournament_broadcast_season (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 server VARCHAR(16) NOT NULL CHECK (server IN ('CN','ASIA','NA','EU','LESTA')),
 year INTEGER NOT NULL CHECK (year BETWEEN 1 AND 9999),
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 start_date DATE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX tournament_broadcast_season_order_idx
 ON tournament_broadcast_season(server, start_date DESC NULLS LAST, created_at DESC, id DESC);
CREATE TABLE tournament_broadcast_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 season_id BIGINT NOT NULL REFERENCES tournament_broadcast_season(id),
 type VARCHAR(24) NOT NULL CHECK (type IN ('POINTS','QUARTER_FINALS','SEMI_FINALS')),
 UNIQUE(season_id, type)
);
CREATE TABLE tournament_broadcast_node (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES tournament_broadcast_category(id),
 root_key INTEGER NOT NULL CHECK (root_key BETWEEN 0 AND 5),
 round_number INTEGER CHECK (round_number BETWEEN 1 AND 5),
 format VARCHAR(16) CHECK (format IN ('ROUND_ROBIN','KNOCKOUT')),
 CHECK ((round_number IS NULL AND root_key = 0) OR (round_number IS NOT NULL AND root_key = round_number AND format IS NULL)),
 UNIQUE(category_id, root_key)
);
-- Retain reservations after business deletion so failed COS cleanup remains retryable.
CREATE TABLE tournament_broadcast_cover (
 id VARCHAR(36) PRIMARY KEY,
 season_id BIGINT REFERENCES tournament_broadcast_season(id) ON DELETE SET NULL,
 object_key VARCHAR(512) NOT NULL UNIQUE,
 status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','READY')),
 content_type VARCHAR(32) NOT NULL CHECK (content_type IN ('image/png','image/jpeg')),
 size BIGINT NOT NULL CHECK (size > 0 AND size <= 10485760),
 hash VARCHAR(64) NOT NULL CHECK (hash ~ '^[a-f0-9]{64}$'),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 unreferenced_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX tournament_broadcast_cover_cleanup_idx ON tournament_broadcast_cover(unreferenced_at);
CREATE TABLE tournament_broadcast_replay (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 node_id BIGINT NOT NULL REFERENCES tournament_broadcast_node(id),
 title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
 url VARCHAR(2048) NOT NULL,
 match_date DATE NOT NULL,
 day_number INTEGER NOT NULL CHECK (day_number > 0),
 group_label VARCHAR(100),
 group_number INTEGER CHECK (group_number BETWEEN 1 AND 4),
 bracket VARCHAR(16) CHECK (bracket IN ('DEFAULT','WINNERS','LOSERS')),
 teams JSONB NOT NULL CHECK (jsonb_typeof(teams) = 'array' AND jsonb_array_length(teams) BETWEEN 2 AND 4),
 perspective VARCHAR(16) NOT NULL CHECK (perspective IN ('POV','OBSERVER')),
 cover_id VARCHAR(36) REFERENCES tournament_broadcast_cover(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX tournament_broadcast_replay_order_idx ON tournament_broadcast_replay(node_id, match_date, id);
CREATE INDEX tournament_broadcast_replay_cover_idx ON tournament_broadcast_replay(cover_id);
